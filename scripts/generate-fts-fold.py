"""Port SQLite's public-domain Unicode folding table, without diacritic removal.
Usage: python3 scripts/generate-fts-fold.py /path/to/fts5_unicode2.c
Source: https://github.com/sqlite/sqlite/blob/master/ext/fts5/fts5_unicode2.c
"""
import hashlib
import pathlib
import re
import sys
source = pathlib.Path(sys.argv[1]).read_bytes()
text = source.decode().split('int sqlite3Fts5UnicodeFold', 1)[1]
entries = re.search(r'aEntry\[\]\s*=\s*\{(.*?)\n  \};', text, re.S).group(1)
ranges = re.findall(r'\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\}', entries)
offsets = re.findall(r'\d+', re.search(r'aiOff\[\]\s*=\s*\{(.*?)\};', text, re.S).group(1))
assert len(ranges) > 150 and len(offsets) > 70
out = '// SQLite public-domain sqlite3Fts5UnicodeFold(..., 0), generated by scripts/generate-fts-fold.py.\n'
out += '// Source: https://github.com/sqlite/sqlite/blob/master/ext/fts5/fts5_unicode2.c\n'
out += f'// Source SHA256: {hashlib.sha256(source).hexdigest()}\n'
out += '///|\nlet fold_ranges : Array[(Int32,Int32,Int32)] = [\n'
out += ''.join(f'  ({a},{b},{c}),\n' for a,b,c in ranges) + ']\n'
out += '///|\nlet fold_offsets : Array[Int32] = [' + ','.join(offsets) + ']\n'
out += '''///|
fn unicode_fold(char : Char) -> Char {
  let c = char.to_int()
  if c < 128 { return fold(char) }
  if c >= 66560 && c < 66600 { return (c + 40).unsafe_to_char() }
  if c >= 65536 { return char }
  let mut low = 0
  let mut high = fold_ranges.length()
  while low < high { let middle = (low + high) / 2; if fold_ranges[middle].0 <= c { low = middle + 1 } else { high = middle } }
  if low == 0 { return char }
  let (start,flags,count) = fold_ranges[low - 1]
  if c < start + count && (1 & flags & (start ^ c)) == 0 { ((c + fold_offsets[flags >> 1]) & 65535).unsafe_to_char() } else { char }
}
'''
pathlib.Path('packages/sqlike/src/fts/unicode_fold.mbt').write_text(out)
