const exec = promisify(execFile);
const generatedHeader = "// Generated by @mizchi/sqlike/vite. Do not edit.\n";
export interface ViteAotCompilation {
  artifact: string;
  files: string[];
  metadata: SqlikeAotBuildInfo;
}

async function compilerIdentity(sourceRoot: string) {
  const parts: string[] = [
    process.version,
    viteVersion,
    await viteCompilerIdentity(sourceRoot),
  ];
  for (const path of ["packages/sqlike", "packages/litestream", "examples/aot"])
    parts.push(await readFile(join(sourceRoot, path, "moon.mod"), "utf8"));
  for (const directory of [
    "packages/sqlike/src/full",
    "packages/litestream/src",
    "examples/aot/src/runtime",
  ])
    for (const file of (await readdir(join(sourceRoot, directory))).sort())
      if (
        (file.endsWith(".mbt") && !/_w?b?test\.mbt$/.test(file)) ||
        file === "moon.pkg"
      )
        parts.push(
          directory,
          file,
          await readFile(join(sourceRoot, directory, file), "utf8"),
        );
  const moon = await exec("moon", ["version", "--all", "--no-path"], {
    timeout: 20_000,
  });
  return digest(JSON.stringify([...parts, moon.stdout]));
}

function declarations(result: ViteAotCompilation) {
  const names = result.metadata.queries
    .map((n) => JSON.stringify(n))
    .join(" | ");
  const core = '"@mizchi/sqlike/aot/core"';
  const execute = `execute(name: ${names}, params?: readonly import(${core}).Value[]): import(${core}).NativeExecution`;
  const connection = result.metadata.api === "connection";
  return (
    generatedHeader +
    `declare module "@mizchi/sqlike/aot" {
  export const artifact: string;
  export const runtime: import(${core}).${connection ? "PortableAotRuntime" : "AotExecutionRuntime"};
  export const metadata: import(${core}).SqlikeAotBuildInfo;
  export const queries: Readonly<{ ${result.metadata.queries.map((n) => `${JSON.stringify(n)}: ${JSON.stringify(n)}`).join("; ")} }>;
  export function openDatabase(${connection ? `image?: string, options?: import(${core}).NativeCompiledOptions` : `options?: import(${core}).AotExecutorOptions`}): Omit<import(${core}).${connection ? "NativeCompiledConnection" : "AotExecutor"}, "execute"> & { ${execute} };
}\n`
  );
}

export class SqlikeViteBuilder {
  private tail: Promise<void> = Promise.resolve();
  private identity?: Promise<string>;
  constructor(
    private root: string,
    private cache: string,
    private sources: string,
    private options: SqlikeAotOptions,
  ) {}
  private async cached(hash: string) {
    try {
      const directory = join(this.cache, hash);
      const seal = JSON.parse(
        await readFile(join(directory, "integrity.json"), "utf8"),
      );
      const code = await readFile(join(directory, "runtime.js"), "utf8");
      if (seal.engineHash === hash && seal.sha256 === digest(code))
        return { code, sha256: seal.sha256 as string };
    } catch (error) {
      if (
        !(error instanceof SyntaxError) &&
        !["ENOENT", "ENOTDIR"].includes(
          (error as NodeJS.ErrnoException).code ?? "",
        )
      )
        throw error;
    }
    return undefined;
  }
  async runtime(hash: string) {
    if (!/^[0-9a-f]{64}$/.test(hash))
      throw Error("invalid SQLike AOT engine hash");
    const runtime = await this.cached(hash);
    if (!runtime)
      throw Error(
        "SQLike AOT cache is incomplete or corrupt; rebuild the AOT module",
      );
    return runtime.code;
  }
  build(): Promise<ViteAotCompilation> {
    const result = this.tail.then(() => this.compile());
    this.tail = result.then(
      () => {},
      () => {},
    );
    return result;
  }
  private async compile(): Promise<ViteAotCompilation> {
    const identity = await (this.identity ??= compilerIdentity(
      this.sources,
    ).catch((error) => {
      this.identity = undefined;
      throw Error(
        `SQLike AOT needs MoonBit on PATH and its build sources: ${(error as Error).message}`,
        { cause: error },
      );
    }));
    for (let attempt = 0; attempt < 3; attempt++) {
      const scanned = await scanSqlikeCatalog(this.root, this.options);
      const built = buildCatalog(scanned.source),
        requirements = analyzeCatalogRequirements(scanned.source);
      const profile = defineSqlike({
        mode: "aot",
        features: [
          ...requirements.features,
          ...(this.options.primaryKeyIndex === false
            ? []
            : ["primaryKeyIndex" as const]),
        ].map((name) => ({ name })),
      });
      const api = this.options.api ?? "execute";
      const apiCapabilities =
        api === "connection"
          ? (["prepared", "snapshot", "transaction"] as const)
          : [];
      const plan = createBuildPlan(profile, {
        requirements,
        hasSecondaryIndexes: catalogHasSecondaryIndexes(
          JSON.parse(built.artifact).schema,
        ),
        apiCapabilities,
        optimizers: this.options.optimizers,
      });
      const exports = selectedAotExports(plan.selected);
      const hash = digest(
        JSON.stringify({
          identity,
          constants: plan.constants,
          exports,
        }),
      );
      let runtime = await this.cached(hash);
      if (!runtime) {
        await buildSqlikeRuntime(profile, {
          catalog: scanned.source,
          outDir: join(this.cache, hash),
          targets: ["js"],
          apiCapabilities,
          optimizers: this.options.optimizers,
          sourceRoot: this.sources,
        });
        const code = await readFile(
          join(this.cache, hash, "runtime.js"),
          "utf8",
        );
        runtime = { code, sha256: digest(code) };
        await writeFile(
          join(this.cache, hash, "integrity.json"),
          JSON.stringify({ engineHash: hash, sha256: runtime.sha256 }),
        );
      }
      if (
        (await scanSqlikeCatalog(this.root, this.options)).fingerprint !==
        scanned.fingerprint
      )
        continue;
      const result: ViteAotCompilation = {
        artifact: built.artifact,
        files: scanned.files,
        metadata: {
          format: "sqlike-vite-aot@1",
          fingerprint: digest(
            scanned.fingerprint + hash + built.manifest.artifactSHA256,
          ),
          engineHash: hash,
          runtimeSHA256: runtime.sha256,
          api,
          files: scanned.files.map((f) =>
            relative(this.root, f).replaceAll("\\", "/"),
          ),
          queries: scanned.source.queries.map((q) => q.name),
          exports,
          runtimeBytes: Buffer.byteLength(runtime.code),
          artifactBytes: Buffer.byteLength(built.artifact),
          requirements,
        },
      };
      if (this.options.dts !== false) {
        const path = resolve(
          this.root,
          this.options.dts ?? "src/sqlike-aot.generated.d.ts",
        );
        let previous: string | undefined;
        try {
          previous = await readFile(path, "utf8");
        } catch (error) {
          if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
        }
        if (previous !== undefined && !previous.startsWith(generatedHeader))
          throw Error(
            `refusing to overwrite non-generated SQLike types: ${path}`,
          );
        const text = declarations(result);
        if (text !== previous) {
          await mkdir(dirname(path), { recursive: true });
          await writeFile(`${path}.tmp`, text);
          await rename(`${path}.tmp`, path);
        }
      }
      return result;
    }
    throw Error(
      "SQL files changed repeatedly during AOT compilation; retry after saving",
    );
  }
}

export function viteAotClient(result: ViteAotCompilation, runtimeId: string) {
  const connection = result.metadata.api === "connection";
  return `import * as runtime from ${JSON.stringify(runtimeId)};
import { ${connection ? "openPortableCompiled" : "openAotExecutor"} } from "@mizchi/sqlike/aot/core";
export { runtime };
export const artifact = ${JSON.stringify(result.artifact)};
export const queries = /* @__PURE__ */ Object.freeze(Object.fromEntries(${JSON.stringify(result.metadata.queries.map((q) => [q, q]))}));
export const metadata = /* @__PURE__ */ Object.freeze(${JSON.stringify(result.metadata)});
export function openDatabase(${connection ? 'image = "", options' : "options"}) {
  return ${connection ? "openPortableCompiled(runtime, artifact, image, options)" : "openAotExecutor(runtime, artifact, options)"};
}\n`;
}
