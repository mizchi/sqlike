import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const read = (path: string) => readFileSync(path, "utf8");
const contract = read("src/runtime-capabilities.json");
const caps = JSON.parse(contract) as {
  format: string;
  functionGroups: Record<string, string[]>;
  expressionGroups: Record<string, string[]>;
  statements: Record<string, string>;
  queryParts: string[];
};
const wireText = read("src/binary-wire.json");
const wire = JSON.parse(wireText) as {
  structs: Record<string, { name: string; type: string }[]>;
  enums: Record<string, { name: string; fields: string[] }[]>;
};
assert.equal(caps.format, "sqlike-runtime-capabilities@1");
const constant = (name: string) => name.replace(/[A-Z]/g, (c) => "_" + c).toUpperCase();
for (const name of [
  ...Object.keys(caps.functionGroups),
  ...Object.keys(caps.expressionGroups),
  ...Object.keys(caps.statements),
  ...caps.queryParts,
])
  assert.match(name, /^[a-z][A-Za-z]*$/);
const hash = (text: string) => createHash("sha256").update(text).digest("hex");
const header = `// Generated by scripts/generate-runtime-capabilities.ts.\n// Capability SHA256: ${hash(contract)}\n// Contract SHA256: ${hash(wireText)}\n`;
const groups = Object.fromEntries(
  Object.keys(caps.functionGroups).map((n) => [n, `CAP_FUNCTION_${constant(n)}`]),
);
const statements = Object.fromEntries(
  Object.keys(caps.statements).map((n) => [n, `CAP_STATEMENT_${constant(n)}`]),
);
const expressions = Object.fromEntries(
  Object.keys(caps.expressionGroups).map((n) => [n, `CAP_EXPRESSION_${constant(n)}`]),
);
const expressionVariants = Object.values(caps.expressionGroups).flat();
assert.equal(new Set(expressionVariants).size, expressionVariants.length);
for (const variant of expressionVariants)
  assert.ok(wire.enums.Expr!.some((v) => v.name === variant), `unknown expression ${variant}`);
const queryParts = Object.fromEntries(caps.queryParts.map((n) => [n, `CAP_QUERY_${constant(n)}`]));
const names = Object.values(caps.functionGroups).flat();
assert.equal(new Set(names).size, names.length, "duplicate function capability");
const config = [header, "///|\nconst CAP_CATALOG_SPECIALIZED : Bool = false"];
for (const name of [
  ...Object.values(groups),
  ...Object.values(expressions),
  ...Object.values(statements),
  ...Object.values(queryParts),
])
  config.push(`///|\nconst ${name} : Bool = true`);
config.push(`///|\nfn runtime_call_capability(name : String, arity : Int32) -> String? {
  if (name == "min" || name == "max") && arity == 1 { return Some("aggregates") }
  match name {
${Object.entries(caps.functionGroups)
  .map(
    ([group, names]) =>
      `${names.map((n) => JSON.stringify(n)).join(" | ")} => Some(${JSON.stringify(group)})`,
  )
  .join("\n")}
    _ => None
  }
}`);
config.push(`///|\nfn runtime_call_allowed(name : String, arity : Int32) -> Bool {
 if (name == "min" || name == "max") && arity == 1 { return CAP_FUNCTION_AGGREGATES }
 match name {
${Object.entries(caps.functionGroups)
  .map(([group, names]) => `${names.map((n) => JSON.stringify(n)).join(" | ")} => ${groups[group]}`)
  .join("\n")}
 _ => true
 }
}`);
config.push(`///|\nfn validate_runtime_call(name : String, arity : Int32) -> Unit raise SqlError {
 if CAP_CATALOG_SPECIALIZED && !runtime_call_allowed(name, arity) { fail("catalog capability disabled: function " + name) }
}`);
config.push(`///|\nfn validate_runtime_query_part(name : String) -> Unit raise SqlError {
 if CAP_CATALOG_SPECIALIZED {
 let enabled = match name {
${Object.entries(queryParts)
  .map(([name, c]) => `${JSON.stringify(name)} => ${c}`)
  .join("\n")}
 _ => false
 }
 guard enabled else { fail("catalog capability disabled: query " + name) }
 }
}`);
config.push(`///|\nfn validate_runtime_statement(name : String) -> Unit raise SqlError {
 if CAP_CATALOG_SPECIALIZED {
 let enabled = match name {
${Object.entries(statements)
  .map(([name, c]) => `${JSON.stringify(name)} => ${c}`)
  .join("\n")}
 _ => false
 }
 guard enabled else { fail("catalog capability disabled: statement " + name) }
 }
}`);
writeFileSync("packages/sqlike/src/full/capability_config_generated.mbt", config.join("\n\n") + "\n");
writeFileSync(
  "src/catalog-capabilities.ts",
  `// Generated by scripts/generate-runtime-capabilities.ts.\nexport const catalogFunctionConstants = ${JSON.stringify(groups, null, 2)} as const;\nexport const catalogExpressionConstants = ${JSON.stringify(expressions, null, 2)} as const;\nexport const catalogStatementConstants = ${JSON.stringify(statements, null, 2)} as const;\nexport const catalogQueryConstants = ${JSON.stringify(queryParts, null, 2)} as const;\nexport type CatalogFunctionGroup = keyof typeof catalogFunctionConstants;\nexport type CatalogExpressionGroup = keyof typeof catalogExpressionConstants;\nexport type CatalogStatementKind = keyof typeof catalogStatementConstants;\nexport type CatalogQueryPart = keyof typeof catalogQueryConstants;\n`,
);

const lines = [
  header,
  "///|\npriv trait RuntimeUsage { fn collect(Self, RuntimeUsageState) -> Unit }",
];
for (const name of ["Int32", "Bool", "String", "Value"])
  lines.push(`///|\nimpl RuntimeUsage for ${name} with fn collect(_, _) { () }`);
lines.push(
  "///|\nimpl[A : RuntimeUsage] RuntimeUsage for Array[A] with fn collect(xs, state) { for x in xs { RuntimeUsage::collect(x, state) } }",
);
lines.push(
  "///|\nimpl[A : RuntimeUsage] RuntimeUsage for A? with fn collect(x, state) { if x is Some(x) { RuntimeUsage::collect(x, state) } }",
);
lines.push(
  "///|\nimpl[A : RuntimeUsage, B : RuntimeUsage] RuntimeUsage for (A, B) with fn collect(x, state) { RuntimeUsage::collect(x.0, state)\nRuntimeUsage::collect(x.1, state) }",
);
for (const [name, fields] of Object.entries(wire.structs).filter(
  ([n]) => !["Store", "StoredRow"].includes(n),
)) {
  const hook =
    name === "ForeignKey"
      ? "state.features = state.features | 1U"
      : name === "TriggerDefinition"
        ? "state.features = state.features | 2U"
        : name === "Table"
          ? "if value.strict == Some(true) { state.features = state.features | 4U }"
          : name === "Source"
            ? "if value.right == Some(true) || value.natural == Some(true) || !value.using_columns.unwrap_or([]).is_empty() { state.features = state.features | 8U }"
            : name === "Selection"
              ? 'state.statements["select"] = true\nfor part in runtime_selection_parts(value) { state.parts[part] = true }'
              : "";
  lines.push(
    `///|\nimpl RuntimeUsage for ${name} with fn collect(value, state) {\n${hook}\n${fields.map((f) => `RuntimeUsage::collect(value.${f.name}, state)`).join("\n")}\n}`,
  );
}
for (const [name, variants] of Object.entries(wire.enums).filter(([n]) => n !== "RowEdit")) {
  const cases = variants.map((v) => {
    const args = v.fields.map((_, i) => `v${i}`);
    const hooks: string[] = [];
    if (name === "DataStatement") {
      const kind = Object.entries(caps.statements).find(([, tag]) => tag === v.name)?.[0];
      assert.ok(kind, `unclassified statement ${v.name}`);
      hooks.push(`state.statements[${JSON.stringify(kind)}] = true`);
      if (v.name === "PreparedPragma")
        hooks.push("state.features = state.features | pragma_features(v0)");
    }
    if (name === "Expr") {
      for (const [group, variants] of Object.entries(caps.expressionGroups))
        if (variants.includes(v.name))
          hooks.push(`state.expressions[${JSON.stringify(group)}] = true`);
      if (v.name === "InSelect") hooks.push('state.parts["inSelect"] = true');
      if (v.name === "Call")
        hooks.push(
          "collect_runtime_call(v0, v1.length(), state)",
          'if runtime_json_value_subtype(v0, v1) { state.parts["jsonSubtype"] = true }',
        );
      if (v.name === "Binary")
        hooks.push('if v0 == "like" { collect_runtime_call("like", 2, state) }');
      if (v.name === "CurrentTime")
        hooks.push("state.features = state.features | 32U", "collect_runtime_call(v0, 1, state)");
      if (v.name === "Window")
        hooks.push(
          "state.features = state.features | 64U",
          "collect_runtime_call(v0, v1.length(), state)",
        );
      if (v.name === "RowNumber")
        hooks.push(
          "state.features = state.features | 64U",
          'collect_runtime_call("row_number", 0, state)',
        );
    }
    if (!args.length && !hooks.length) return `${v.name} => ()`;
    return `${v.name}${args.length ? `(${args.join(", ")})` : ""} => {\n${hooks.join("\n")}\n${args.map((a) => `RuntimeUsage::collect(${a}, state)`).join("\n")}\n}`;
  });
  lines.push(
    `///|\nimpl RuntimeUsage for ${name} with fn collect(value, state) { match value {\n${cases.join("\n")}\n} }`,
  );
}
writeFileSync("packages/sqlike/src/full/runtime_usage_generated.mbt", lines.join("\n\n") + "\n");
