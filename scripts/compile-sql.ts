import { readFileSync, writeFileSync, mkdirSync, renameSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { buildCatalog } from "./aot-compiler.ts";
import type { CatalogSource } from "../src/aot-contract.ts";
const [input, output, ...extra] = process.argv.slice(2);
if (!input || !output || extra.length)
  throw Error(
    "usage: pnpm exec tsx scripts/compile-sql.ts source.json output-prefix",
  );
const result = buildCatalog(
  JSON.parse(readFileSync(resolve(input), "utf8")) as CatalogSource,
);
const prefix = resolve(output);
mkdirSync(dirname(prefix), { recursive: true });
for (const [path, data] of [
  [`${prefix}.json`, result.artifact],
  [`${prefix}.manifest.json`, JSON.stringify(result.manifest, null, 2) + "\n"],
  [
    `${prefix}.ts`,
    `// Generated by compile-sql.ts; do not edit.\nexport const artifact=${JSON.stringify(result.artifact)};\nexport const manifest=${JSON.stringify(result.manifest)} as const;\n`,
  ],
]) {
  writeFileSync(`${path}.tmp`, data!);
  renameSync(`${path}.tmp`, path!);
}
console.log(
  `compiled ${result.manifest.queries.length} queries; artifact ${Buffer.byteLength(result.artifact)} bytes; SQLite template ${Buffer.from(result.storage.image, "base64").length} bytes`,
);
