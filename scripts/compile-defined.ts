import { readFileSync, writeFileSync, mkdirSync, renameSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { buildDefinedCatalog } from "./defined-compiler.ts";
import type { CatalogSource } from "../src/aot-contract.ts";
const [input, output, ...flags] = process.argv.slice(2);
if (
  !input ||
  !output ||
  flags.some((f) => f !== "--sqlite-export") ||
  flags.length > 1
)
  throw Error(
    "usage: compile-defined.ts source.json output-prefix [--sqlite-export]",
  );
const catalog = buildDefinedCatalog(
  JSON.parse(readFileSync(resolve(input), "utf8")) as CatalogSource,
  { sqliteExport: flags.includes("--sqlite-export") },
);
const prefix = resolve(output);
mkdirSync(dirname(prefix), { recursive: true });
const files: [string, string | Uint8Array][] = [
  [prefix + ".schema.bin", catalog.schema],
  [prefix + ".statements.bin", catalog.statements],
  [prefix + ".manifest.json", JSON.stringify(catalog.manifest, null, 2) + "\n"],
  [
    prefix + ".ts",
    `// Generated by compile-defined.ts; data only.\nexport const schema=new Uint8Array(${JSON.stringify([...catalog.schema])});\nexport const statements=new Uint8Array(${JSON.stringify([...catalog.statements])});\nexport const manifest=${JSON.stringify(catalog.manifest)} as const;\nexport const catalog={schema,statements,manifest};\n`,
  ],
];
if (catalog.storage) files.push([prefix + ".sqlite.bin", catalog.storage]);
for (const [path, bytes] of files) {
  writeFileSync(path + ".tmp", bytes);
  renameSync(path + ".tmp", path);
}
console.log({
  queries: catalog.manifest.queries.length,
  schemaBytes: catalog.schema.length,
  statementBytes: catalog.statements.length,
  optionalSQLiteBytes: catalog.storage?.length ?? 0,
  schemaId: catalog.manifest.schemaId,
});
