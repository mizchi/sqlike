import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import {
  generateSQLiteDrizzleJson,
  generateSQLiteMigration,
} from "drizzle-kit/api";
import { readMigrationFiles } from "drizzle-orm/migrator";
import { schemaAt } from "../tests/fixtures/drizzle/schema.ts";
const root = "tests/fixtures/drizzle/migrations";
mkdirSync(join(root, "meta"), { recursive: true });
const entries = [];
let previous = await generateSQLiteDrizzleJson({});
previous.id = "00000000-0000-0000-0000-000000000000";
for (let version = 0; version < 8; version++) {
  const current = await generateSQLiteDrizzleJson(
    schemaAt(version),
    previous.id,
  );
  current.id = `00000000-0000-0000-0000-${String(version + 1).padStart(12, "0")}`;
  const names = [
    "initial",
    "add_column_index",
    "drop_column",
    "change_type_default",
    "constraints_partial_index",
    "rebuild_drop_column",
    "rename_custom",
    "view_trigger_custom",
  ];
  const statements =
    version < 6
      ? await generateSQLiteMigration(previous, current)
      : version === 6
        ? [
            'ALTER TABLE "users" RENAME TO "members";',
            'ALTER TABLE "members" RENAME COLUMN "name" TO "display_name";',
          ]
        : [
            'CREATE TABLE "audit" ("id" INTEGER PRIMARY KEY,"member_id" INTEGER,"event" TEXT);',
            'CREATE VIEW "member_names" AS SELECT "id","display_name" FROM "members";',
            'CREATE INDEX "name_desc" ON "members"("display_name" DESC,"id");',
            'CREATE INDEX "live_name" ON "members"(lower("display_name")) WHERE "score">0;',
            `CREATE TRIGGER "member_added" AFTER INSERT ON "members" BEGIN INSERT INTO "audit"("member_id","event") VALUES(new.id,'insert'); END;`,
          ];
  const tag = `${String(version).padStart(4, "0")}_${names[version]}`;
  writeFileSync(
    join(root, `${tag}.sql`),
    statements.join("\n--> statement-breakpoint\n") + "\n",
  );
  writeFileSync(
    join(root, "meta", `${String(version).padStart(4, "0")}_snapshot.json`),
    JSON.stringify(current, null, 2) + "\n",
  );
  entries.push({
    idx: version,
    version: "6",
    when: 1760000000000 + version * 1000,
    tag,
    breakpoints: true,
  });
  previous = current;
}
writeFileSync(
  join(root, "meta", "_journal.json"),
  JSON.stringify({ version: "7", dialect: "sqlite", entries }, null, 2) + "\n",
);
writeFileSync(
  "tests/fixtures/drizzle/migrations.generated.ts",
  `// Generated by scripts/generate-drizzle-fixtures.ts; no Node runtime imports.\nexport const migrations = ${JSON.stringify(readMigrationFiles({ migrationsFolder: root }), null, 2)};\n`,
);
console.log({
  orm: JSON.parse(readFileSync("node_modules/drizzle-orm/package.json", "utf8"))
    .version,
  kit: JSON.parse(readFileSync("node_modules/drizzle-kit/package.json", "utf8"))
    .version,
  migrations: entries.length,
});
